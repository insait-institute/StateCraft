// Pipeline player: replays a recorded closed-loop run step by step. Nothing runs live: every
// frame, click and language-model output was saved by one offline run and is only animated here.
//
// <script src="./static/player/pipeline/data.js"></script>
// <div class="pipeline-player" data-src="./static/player/pipeline/data.json"></div>
//
// Data: {frame_w, frame_h, start_img, steps: [{frame, img, action: {type, gx, gy, name},
//        llm: {kind, text, raw} | null, gate: {skip, p} | undefined, branch: id | undefined}],
//        branches: {id: {prompt, choices: [{id, label, note, steps: [...] | undefined}]}}}
// gx, gy are the click on a 0-100 grid of the frame. A choice without steps is the recording.
(function () {
  'use strict';

  var REDUCED = window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  var SPEED = 0.5;              // same half speed as the page videos
  var TYPE_MS_PER_CHAR = 6 / SPEED;
  var TIMING = { move: 450, click: 320, typeMax: 1100, typeMin: 250, fade: 260, hold: 650 };
  Object.keys(TIMING).forEach(function (k) { TIMING[k] /= SPEED; });
  var ACTION_WORDS = { click: 'click', double_click: 'double-click', right_click: 'right-click',
                       menu_click: 'menu click', key_combo: 'keys', system: 'system' };

  function el(tag, cls, text) {
    var e = document.createElement(tag);
    if (cls) e.className = cls;
    if (text !== undefined) e.textContent = text;
    return e;
  }

  function wait(ms) {
    return new Promise(function (resolve) { setTimeout(resolve, REDUCED ? 0 : ms); });
  }

  function preload(src) {
    return new Promise(function (resolve) {
      var img = new Image();
      img.onload = img.onerror = function () { resolve(img); };
      img.src = src;
    });
  }

  function Player(root, data, base) {
    this.root = root;
    root.style.setProperty('--pp-fade', TIMING.fade + 'ms');
    root.style.setProperty('--pp-click', TIMING.click + 'ms');
    this.data = data;
    this.base = base;
    this.i = 0;                 // next recorded step to play
    this.playing = false;
    this.busy = false;
    this.token = 0;             // bumps on every user jump; stale animations stop
    this.build();
    this.showStill(data.start_img, null);
    this.renderControls();
  }

  Player.prototype.url = function (p) { return this.base + p; };

  Player.prototype.build = function () {
    var d = this.data;
    var r = this.root;
    r.classList.add('pp-ready');
    var stage = el('div', 'pp-stage');
    this.screen = el('div', 'pp-screen');
    this.screen.style.aspectRatio = d.frame_w + ' / ' + d.frame_h;
    this.imgA = el('img', 'pp-frame');
    this.imgB = el('img', 'pp-frame pp-frame-next');
    this.imgA.alt = this.imgB.alt = 'Frame generated by the video model';
    this.cursor = el('div', 'pp-cursor');
    this.cursor.innerHTML = '<svg viewBox="0 0 24 24" aria-hidden="true"><path d="M3 2l7.5 19 2.6-7.4L20.5 11z"/></svg>';
    this.ripple = el('div', 'pp-ripple');
    this.badge = el('div', 'pp-badge');
    this.screen.append(this.imgA, this.imgB, this.ripple, this.cursor, this.badge);
    stage.appendChild(this.screen);

    var side = el('div', 'pp-side');
    this.actionLine = el('div', 'pp-action');
    var gateWrap = el('div', 'pp-gate');
    this.gateLine = el('div', 'pp-gate-line');
    gateWrap.append(el('div', 'pp-label', 'Event gate'), this.gateLine);
    if (!d.gate) gateWrap.hidden = true;
    var llmWrap = el('div', 'pp-llm');
    var llmHead = el('div', 'pp-label');
    llmHead.append(document.createTextNode('Language model: next state '));
    this.rawToggle = el('button', 'pp-raw-toggle', 'raw output');
    this.rawToggle.type = 'button';
    llmHead.appendChild(this.rawToggle);
    this.llmBox = el('pre', 'pp-llm-box');
    this.llmBox.setAttribute('aria-live', 'polite');
    this.llmNote = el('div', 'pp-note', d.llm_note || '');
    llmWrap.append(llmHead, this.llmBox, this.llmNote);
    var renderWrap = el('div', 'pp-render');
    this.renderLine = el('div', 'pp-render-line', 'Waiting for the first action');
    renderWrap.append(el('div', 'pp-label', 'Video model: next frame'), this.renderLine);
    side.append(this.actionLine, gateWrap, llmWrap, renderWrap);
    stage.appendChild(side);

    this.choices = el('div', 'pp-choices');
    this.choices.hidden = true;
    var controls = el('div', 'pp-controls');
    this.btnPrev = el('button', 'button is-small is-rounded', 'Restart');
    this.btnPlay = el('button', 'button is-small is-rounded is-dark', 'Play');
    this.btnNext = el('button', 'button is-small is-rounded', 'Step');
    [this.btnPrev, this.btnPlay, this.btnNext].forEach(function (b) { b.type = 'button'; });
    this.progress = el('span', 'pp-progress');
    controls.append(this.btnPrev, this.btnPlay, this.btnNext, this.progress);
    r.append(stage, this.choices, controls);

    var self = this;
    this.btnPlay.addEventListener('click', function () { self.setPlaying(!self.playing); });
    this.btnNext.addEventListener('click', function () { self.setPlaying(false); self.next(); });
    this.btnPrev.addEventListener('click', function () { self.restart(); });
    this.rawToggle.addEventListener('click', function () {
      self.showRaw = !self.showRaw;
      self.rawToggle.classList.toggle('is-active', self.showRaw);
      if (self.lastLlm) self.llmBox.textContent = self.llmText(self.lastLlm);
    });
  };

  Player.prototype.llmText = function (llm) {
    if (!llm) return '';
    return this.showRaw && llm.raw ? llm.raw : llm.text;
  };

  Player.prototype.renderControls = function () {
    var n = this.data.steps.length;
    this.progress.textContent = 'Step ' + Math.min(this.i, n) + ' / ' + n;
    this.btnPlay.textContent = this.playing ? 'Pause' : (this.i >= n ? 'Replay' : 'Play');
    this.btnNext.disabled = this.busy || this.i >= n || !this.choices.hidden;
  };

  Player.prototype.setPlaying = function (on) {
    if (on && this.i >= this.data.steps.length) this.restart();
    this.playing = on;
    this.renderControls();
    if (on) this.loop();
  };

  Player.prototype.loop = function () {
    var self = this;
    if (!this.playing || this.busy) return;
    this.next().then(function (ok) {
      if (ok && self.playing) return wait(TIMING.hold).then(function () { self.loop(); });
      self.playing = false;
      self.renderControls();
    });
  };

  Player.prototype.restart = function () {
    this.token++;
    this.busy = false;
    this.i = 0;
    this.choices.hidden = true;
    this.showStill(this.data.start_img, null);
    this.llmBox.textContent = '';
    this.lastLlm = null;
    this.actionLine.textContent = '';
    this.gateLine.textContent = '';
    this.renderLine.textContent = 'Waiting for the first action';
    this.renderControls();
  };

  Player.prototype.showStill = function (img, action) {
    this.imgA.src = this.url(img);
    this.imgB.classList.remove('is-shown');
    this.cursorAt(action ? action.gx : 50, action ? action.gy : 60, true);
  };

  Player.prototype.cursorAt = function (gx, gy, instant) {
    this.cursor.style.transition = instant || REDUCED ? 'none' : 'left ' + TIMING.move + 'ms ease, top ' + TIMING.move + 'ms ease';
    this.cursor.style.left = gx + '%';
    this.cursor.style.top = gy + '%';
  };

  // Plays the recorded step i, or offers the branch choices first when step i is a branch point.
  Player.prototype.next = function () {
    var step = this.data.steps[this.i];
    if (!step || this.busy) return Promise.resolve(false);
    if (step.branch && !this.branchDone) return this.offer(step.branch);
    this.branchDone = false;
    var self = this;
    return this.play(step).then(function (ok) {
      if (ok) self.i++;
      self.renderControls();
      return ok;
    });
  };

  Player.prototype.offer = function (id) {
    var b = this.data.branches[id];
    var self = this;
    this.playing = false;
    this.choices.innerHTML = '';
    this.choices.appendChild(el('span', 'pp-choices-prompt', b.prompt));
    b.choices.forEach(function (c) {
      var btn = el('button', 'pp-choice' + (c.steps ? '' : ' is-recorded'));
      btn.type = 'button';
      btn.append(el('strong', '', c.label), el('span', 'pp-choice-note', c.note));
      btn.addEventListener('click', function () { self.choose(c); });
      self.choices.appendChild(btn);
    });
    this.choices.hidden = false;
    this.renderControls();
    return Promise.resolve(false);
  };

  Player.prototype.choose = function (choice) {
    var self = this;
    if (this.busy) return;
    if (!choice.steps) {                       // the recording: continue it
      this.choices.hidden = true;
      this.branchDone = true;
      this.setPlaying(true);
      return;
    }
    this.choices.hidden = true;
    var from = this.i > 0 ? this.data.steps[this.i - 1] : null;
    var seq = Promise.resolve(true);
    choice.steps.forEach(function (s) {
      seq = seq.then(function (ok) { return ok && self.play(s).then(function (r) { return r && wait(TIMING.hold).then(function () { return true; }); }); });
    });
    seq.then(function (ok) {
      if (!ok) return;
      // Back on the recording: the state before the branch point, and the choices again.
      self.showStill(from ? from.img : self.data.start_img, from ? from.action : null);
      self.renderLine.textContent = 'Back on the recording';
      self.offer(self.data.steps[self.i].branch);
    });
  };

  Player.prototype.play = function (step) {
    var self = this;
    var token = ++this.token;
    var alive = function () { return token === self.token; };
    var a = step.action;
    this.busy = true;
    this.renderControls();
    this.actionLine.innerHTML = '';
    this.actionLine.append(el('span', 'pp-label', 'Action'),
      el('span', 'pp-action-text', (ACTION_WORDS[a.type] || a.type) + (a.name ? ' · ' + a.name : '')));
    this.llmBox.textContent = '';
    this.renderLine.textContent = '';
    var gate = step.gate;
    this.gateLine.textContent = '';
    var ready = preload(this.url(step.img));
    this.cursorAt(a.gx, a.gy, false);
    return wait(TIMING.move).then(function () {
      if (!alive()) return false;
      return self.click(a.type === 'double_click' ? 2 : 1);
    }).then(function (ok) {
      if (ok === false || !alive()) return false;
      if (gate) {
        self.gateLine.textContent = 'P(no change) = ' + gate.p.toFixed(2) + (gate.skip ? '  → skip the language model, keep the state' : '  → call the language model') +
          (gate.missed ? '. The state did change here: a missed update.' : '');
        self.gateLine.className = 'pp-gate-line ' + (gate.missed ? 'is-missed' : gate.skip ? 'is-skip' : 'is-call');
        if (gate.skip) {
          self.llmBox.textContent = '(not called)';
          self.lastLlm = null;
          return wait(TIMING.typeMin);
        }
      }
      self.lastLlm = step.llm;
      return self.type(self.llmText(step.llm), alive);
    }).then(function (ok) {
      if (ok === false || !alive()) return false;
      self.renderLine.textContent = 'generating…';
      return ready;
    }).then(function (img) {
      if (!alive() || img === false) return false;
      self.imgB.src = img.src;
      self.imgB.classList.add('is-shown');
      return wait(TIMING.fade).then(function () {
        if (!alive()) return false;
        self.imgA.src = img.src;
        self.imgB.classList.remove('is-shown');
        self.renderLine.textContent = 'frame ' + step.frame + (step.note ? ' · ' + step.note : '');
        self.badge.textContent = step.badge || '';
        self.badge.hidden = !step.badge;
        self.busy = false;
        return true;
      });
    });
  };

  Player.prototype.click = function (n) {
    var self = this;
    this.ripple.style.left = this.cursor.style.left;
    this.ripple.style.top = this.cursor.style.top;
    var seq = Promise.resolve();
    for (var k = 0; k < n; k++) {
      seq = seq.then(function () {
        self.ripple.classList.remove('is-on');
        void self.ripple.offsetWidth;            // restart the CSS animation
        self.ripple.classList.add('is-on');
        return wait(TIMING.click / 2);
      });
    }
    return seq.then(function () { return wait(TIMING.click / 2); });
  };

  Player.prototype.type = function (text, alive) {
    var box = this.llmBox;
    if (REDUCED || !text) { box.textContent = text || ''; return Promise.resolve(true); }
    var total = Math.max(TIMING.typeMin, Math.min(TIMING.typeMax, text.length * TYPE_MS_PER_CHAR));
    var start = performance.now();
    return new Promise(function (resolve) {
      function frame(now) {
        if (!alive()) return resolve(false);
        var n = Math.min(text.length, Math.ceil(text.length * (now - start) / total));
        box.textContent = text.slice(0, n);
        box.scrollTop = box.scrollHeight;
        if (n < text.length) requestAnimationFrame(frame); else resolve(true);
      }
      requestAnimationFrame(frame);
    });
  };

  // Data comes from the included data.js (window.PIPELINE_PLAYER[<folder name>]), which also
  // works when the page is opened from disk; data.json next to it is fetched otherwise.
  function init() {
    var roots = document.querySelectorAll('.pipeline-player[data-src]');
    Array.prototype.forEach.call(roots, function (root) {
      var src = root.getAttribute('data-src');
      var base = src.slice(0, src.lastIndexOf('/') + 1);
      var key = base.replace(/\/$/, '').split('/').pop();
      var inline = window.PIPELINE_PLAYER && window.PIPELINE_PLAYER[key];
      if (inline) {
        root.player = new Player(root, inline, base);
        return;
      }
      fetch(src).then(function (r) {
        if (!r.ok) throw new Error(r.status);
        return r.json();
      }).then(function (data) {
        root.player = new Player(root, data, base);
      }).catch(function () {
        root.classList.add('pp-missing');
        root.textContent = 'Player data not added yet (' + src + ').';
      });
    });
  }

  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init);
  else init();
})();
